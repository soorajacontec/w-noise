import fs from 'fs';
import {feature} from 'topojson-client';
import {geoContains} from 'd3-geo';
const topo = JSON.parse(fs.readFileSync('node_modules/world-atlas/land-110m.json'));
const land = feature(topo, topo.objects.land);
const W=1000,H=500,S=7; let d='';let n=0;
for(let y=S/2;y<H;y+=S)for(let x=S/2;x<W;x+=S){
  const lon=x/W*360-180, lat=90-y/H*180;
  if(geoContains(land,[lon,lat])){d+=`M${x.toFixed(1)} ${y.toFixed(1)}h0`;n++;}
}
fs.writeFileSync(process.argv[2],`/* Generated by tools/build-map.mjs from Natural Earth land (world-atlas, 110m). Equirectangular 1000x500, one dot every ${S}px. */\nwindow.WN_MAP={w:${W},h:${H},step:${S},d:"${d}"};\n`);
console.log(n, d.length);
